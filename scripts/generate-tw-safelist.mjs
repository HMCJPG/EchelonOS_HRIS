/**
 * Workaround for Windows-on-ARM + Smart App Control: SAC blocks Tailwind's
 * unsigned native oxide binary, and the WASI fallback can't walk the Windows
 * filesystem (scanner returns 0 candidates), so no utilities get generated.
 *
 * This script does the scanning in plain Node using Tailwind v3's battle-tested
 * default extractor regex and emits the candidates as `@source inline(...)`
 * rules, which the (working) WASM engine turns into CSS. Runs on predev/prebuild;
 * redundant-but-harmless on platforms where the native scanner works.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const EXTS = new Set([".ts", ".tsx", ".js", ".jsx", ".mdx"]);
const EXTRACTOR = /[^<>"'`\s]*[^<>"'`\s:]/g;

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory() && entry.name !== "node_modules") yield* walk(p);
    if (entry.isFile() && EXTS.has(p.slice(p.lastIndexOf(".")))) yield p;
  }
}

const candidates = new Set();
for (const file of [...walk("src")]) {
  const content = readFileSync(file, "utf8");
  for (const token of content.match(EXTRACTOR) ?? []) {
    // Skip anything that would confuse @source inline's syntax (brace
    // expansion, escapes) or is obviously not a class.
    if (token.length > 80) continue;
    if (/[{}$\\"']/.test(token)) continue;
    candidates.add(token);
  }
}

const sorted = [...candidates].sort();
const lines = sorted.map((c) => `@source inline("${c}");`);
writeFileSync(
  "src/app/tw-safelist.css",
  `/* AUTO-GENERATED by scripts/generate-tw-safelist.mjs — do not edit. */\n${lines.join("\n")}\n`,
);
console.log(`tw-safelist: ${sorted.length} candidates written`);
